func (g RustGenerator) canGenerateBorrowed(pkt *model.Packet) bool {
	return g.canGenerateBorrowedPacket(pkt, make(map[*model.Packet]uint8))
}

func (g RustGenerator) hasBorrowedCode(pkt *model.Packet) bool {
	if g.canGenerateBorrowed(pkt) {
		return true
	}
	for _, f := range pkt.Fields {
		if object, ok := f.Attr.(*model.ObjectFieldAttribute); ok && object.IsIner {
			if g.hasBorrowedCode(object.RefPacket) {
				return true
			}
		}
	}
	return false
}

func (g RustGenerator) canGenerateBorrowedPacket(pkt *model.Packet, state map[*model.Packet]uint8) bool {
	if pkt == nil {
		return false
	}
	if state[pkt] == 1 {
		return false
	}
	if state[pkt] == 2 {
		return true
	}
	state[pkt] = 1
	for _, f := range pkt.Fields {
		if f.IsRepeat {
			return false
		}
		switch attr := f.Attr.(type) {
		case *model.FixedStringFieldAttribute, *model.DynamicStringFieldAttribute,
			*model.BasicFieldAttribute, *model.LengthFieldAttribute, *model.CheckSumFieldAttribute:
		case *model.ObjectFieldAttribute:
			if !g.canGenerateBorrowedPacket(attr.RefPacket, state) {
				return false
			}
		case *model.MatchFieldAttribute:
			for _, pair := range attr.MatchPairs {
				if !g.canGenerateBorrowedPacket(g.binModel.PacketsMap[pair.Value], state) {
					return false
				}
			}
		default:
			return false
		}
	}
	state[pkt] = 2
	return true
}

func (g RustGenerator) generateBorrowedCode(pkt *model.Packet) string {
	var b strings.Builder
	for _, f := range pkt.Fields {
		if object, ok := f.Attr.(*model.ObjectFieldAttribute); ok && object.IsIner {
			b.WriteString(g.generateBorrowedCode(object.RefPacket))
			b.WriteString("\n")
		}
	}
	if !g.canGenerateBorrowed(pkt) {
		return b.String()
	}
	b.WriteString(g.generateBorrowedMatchFieldEnumCode(pkt))
	structName := strcase.ToCamel(pkt.Name)
	b.WriteString("#[derive(Debug, Clone, Copy, PartialEq)]\n")
	b.WriteString(fmt.Sprintf("pub struct %sRef<'a> {\n", structName))
	for _, f := range pkt.Fields {
		b.WriteString(AddIndent4ln(fmt.Sprintf("pub %s: %s,", g.GetFieldName(f), g.getBorrowedFieldType(structName, f))))
	}
	b.WriteString(AddIndent4ln("_marker: std::marker::PhantomData<&'a ()>,"))
	b.WriteString("}\n\n")
	b.WriteString(fmt.Sprintf("impl<'a> %sRef<'a> {\n", structName))
	b.WriteString(AddIndent4ln("#[inline]"))
	b.WriteString(AddIndent4ln("pub fn from_slice(input: &'a [u8]) -> Option<Self> {"))
	b.WriteString(AddIndent4ln(AddIndent4("let mut reader = BorrowedReader::new(input);")))
	b.WriteString(AddIndent4ln(AddIndent4("Self::decode_ref(&mut reader)")))
	b.WriteString(AddIndent4ln("}"))
	b.WriteString("\n")
	b.WriteString(AddIndent4ln("#[inline]"))
	readerName := "reader"
	if len(pkt.Fields) == 0 {
		readerName = "_reader"
	}
	b.WriteString(AddIndent4ln(fmt.Sprintf("pub fn decode_ref(%s: &mut BorrowedReader<'a>) -> Option<Self> {", readerName)))
	for _, f := range pkt.Fields {
		b.WriteString(AddIndent4ln(AddIndent4(g.decodeBorrowedField(structName, f))))
	}
	b.WriteString(AddIndent4ln(AddIndent4("Some(Self {")))
	for _, f := range pkt.Fields {
		b.WriteString(AddIndent4ln(AddIndent4(AddIndent4(g.GetFieldName(f) + ","))))
	}
	b.WriteString(AddIndent4ln(AddIndent4(AddIndent4("_marker: std::marker::PhantomData,"))))
	b.WriteString(AddIndent4ln(AddIndent4("})")))
	b.WriteString(AddIndent4ln("}"))
	b.WriteString("}\n")
	return b.String()
}

func (g RustGenerator) generateBorrowedMatchFieldEnumCode(pkt *model.Packet) string {
	var b strings.Builder
	for _, f := range pkt.Fields {
		match, ok := f.Attr.(*model.MatchFieldAttribute)
		if !ok {
			continue
		}
		b.WriteString("#[derive(Debug, Clone, Copy, PartialEq)]\n")
		b.WriteString(fmt.Sprintf("pub enum %s%sRefEnum<'a> {\n", strcase.ToCamel(pkt.Name), f.Name))
		seen := make(map[string]struct{})
		for _, pair := range match.MatchPairs {
			if _, exists := seen[pair.Value]; exists {
				continue
			}
			seen[pair.Value] = struct{}{}
			b.WriteString(fmt.Sprintf("    %s(%sRef<'a>),\n", pair.Value, strcase.ToCamel(pair.Value)))
		}
		b.WriteString("}\n\n")
	}
	return b.String()
}

func (g RustGenerator) getBorrowedFieldType(parentName string, f *model.Field) string {
	switch attr := f.Attr.(type) {
	case *model.FixedStringFieldAttribute, *model.DynamicStringFieldAttribute:
		return "&'a str"
	case *model.MatchFieldAttribute:
		return parentName + f.Name + "RefEnum<'a>"
	case *model.ObjectFieldAttribute:
		return strcase.ToCamel(attr.RefPacket.Name) + "Ref<'a>"
	default:
		return f.GetType()
	}
}

func (g RustGenerator) decodeBorrowedField(parentName string, f *model.Field) string {
	name := g.GetFieldName(f)
	padding := g.GetPadding(f)
	switch attr := f.Attr.(type) {
	case *model.FixedStringFieldAttribute:
		return fmt.Sprintf("let %s = reader.get_fixed_str(%d, b%s, %t)?;", name, attr.Length, padding.PadChar, padding.PadLeft)
	case *model.DynamicStringFieldAttribute:
		length := g.borrowedReaderCall(g.GetConfig().StringLenPrefixLenType)
		return fmt.Sprintf("let %s_wire_len = %s as usize;\nlet %s = reader.get_str(%s_wire_len)?;", name, length, name, name)
	case *model.MatchFieldAttribute:
		return g.decodeBorrowedMatchField(parentName, f, attr)
	case *model.ObjectFieldAttribute:
		return fmt.Sprintf("let %s = %sRef::decode_ref(reader)?;", name, strcase.ToCamel(attr.RefPacket.Name))
	default:
		return fmt.Sprintf("let %s = %s;", name, g.borrowedReaderCall(f.GetType()))
	}
}

func (g RustGenerator) decodeBorrowedMatchField(parentName string, f *model.Field, match *model.MatchFieldAttribute) string {
	matchKey := g.GetFieldName(match.MatchKeyField)
	var b strings.Builder
	b.WriteString(fmt.Sprintf("let %s = match %s {\n", g.GetFieldName(f), matchKey))
	seen := make(map[string]struct{})
	for _, pair := range match.MatchPairs {
		if _, exists := seen[pair.Key]; exists {
			continue
		}
		seen[pair.Key] = struct{}{}
		b.WriteString(AddIndent4ln(fmt.Sprintf("%s => %s%sRefEnum::%s(%sRef::decode_ref(reader)?),", pair.Key, parentName, f.Name, pair.Value, strcase.ToCamel(pair.Value))))
	}
	b.WriteString(AddIndent4ln("_ => return None,"))
	b.WriteString("};")
	return b.String()
}

func (g RustGenerator) borrowedReaderCall(fieldType string) string {
	suffix := ""
	if g.GetConfig().LittleEndian && fieldType != "u8" && fieldType != "i8" && fieldType != "char" {
		suffix = "_le"
	}
	if fieldType == "char" {
		return "reader.get_char()?"
	}
	return fmt.Sprintf("reader.get_%s%s()?", fieldType, suffix)
}
