// generateTests emits a single tests.c with one round-trip test per packet
// and a main() runner (no external test framework required).
func (g CGenerator) generateTests() string {
	var b strings.Builder
	b.WriteString("/* Code generated by fin-protoc. DO NOT EDIT. */\n")
	b.WriteString("#include \"root.h\"\n")
	b.WriteString("#include <stdio.h>\n")
	b.WriteString("#include <stdlib.h>\n")
	b.WriteString("#include <string.h>\n\n")
	b.WriteString("#define CHECK(x) \\\n")
	b.WriteString("    do { \\\n")
	b.WriteString("        if (!(x)) { \\\n")
	b.WriteString("            fprintf(stderr, \"CHECK failed: %s (%s:%d)\\n\", #x, __FILE__, __LINE__); \\\n")
	b.WriteString("            exit(1); \\\n")
	b.WriteString("        } \\\n")
	b.WriteString("    } while (0)\n\n")

	endian := 0
	if g.GetConfig().LittleEndian {
		endian = 1
	}
	for _, pkt := range g.orderedPackets() {
		t := g.cTypeName(pkt)
		b.WriteString(fmt.Sprintf("static void test_%s_codec(void) {\n", strcase.ToSnake(pkt.Name)))
		b.WriteString(fmt.Sprintf("    %s msg;\n", t))
		b.WriteString("    memset(&msg, 0, sizeof(msg));\n")
		for _, line := range g.testAssignments(pkt, "msg") {
			b.WriteString("    " + line + "\n")
		}
		b.WriteString("\n    fc_buffer buf;\n")
		b.WriteString(fmt.Sprintf("    fc_buffer_init(&buf, %d);\n", endian))
		b.WriteString(fmt.Sprintf("    CHECK(%s_encode(&msg, &buf));\n", t))
		b.WriteString("\n    fc_reader reader;\n")
		b.WriteString(fmt.Sprintf("    fc_reader_init(&reader, buf.data, buf.len, %d);\n", endian))
		b.WriteString(fmt.Sprintf("    %s decoded;\n", t))
		b.WriteString(fmt.Sprintf("    CHECK(%s_decode(&reader, &decoded));\n", t))
		for _, f := range pkt.Fields {
			switch f.Attr.(type) {
			case *model.LengthFieldAttribute, *model.CheckSumFieldAttribute:
				b.WriteString(fmt.Sprintf("    msg.%s = decoded.%s;\n", cSnake(f.Name), cSnake(f.Name)))
			}
		}
		b.WriteString(fmt.Sprintf("    CHECK(%s_eql(&msg, &decoded));\n", t))
		b.WriteString(fmt.Sprintf("    %s_free(&decoded);\n", t))
		b.WriteString("    fc_buffer_free(&buf);\n")
		b.WriteString("}\n\n")
	}

	b.WriteString("int main(void) {\n")
	for _, pkt := range g.orderedPackets() {
		b.WriteString(fmt.Sprintf("    test_%s_codec();\n", strcase.ToSnake(pkt.Name)))
	}
	b.WriteString("    printf(\"all tests passed\\n\");\n")
	b.WriteString("    return 0;\n")
	b.WriteString("}\n")
	return b.String()
}

// testAssignments builds the C assignment statements constructing a sample
// instance of the packet at the given base path (e.g. "msg").
func (g CGenerator) testAssignments(pkt *model.Packet, path string) []string {
	var lines []string
	for _, f := range pkt.Fields {
		name := cSnake(f.Name)
		if mf, ok := f.Attr.(*model.MatchFieldAttribute); ok {
			if len(mf.MatchPairs) == 0 {
				continue
			}
			key := mf.MatchPairs[0].Key
			if g.HasQuotes(key) {
				lines = append(lines, fmt.Sprintf("%s.%s = FC_STR(%s);", path, cSnake(mf.MatchKeyField.Name), key))
			} else {
				lines = append(lines, fmt.Sprintf("%s.%s = %s;", path, cSnake(mf.MatchKeyField.Name), key))
			}
			first := mf.MatchPairs[0].Value
			lines = append(lines, fmt.Sprintf("%s.%s_tag = %s;", path, name, g.matchKindConstant(pkt, f, first)))
			if sub, ok := g.binModel.PacketsMap[first]; ok {
				lines = append(lines, g.testAssignments(sub, fmt.Sprintf("%s.%s.%s", path, name, cSnake(first)))...)
			}
			continue
		}
		if pkt.MatchFields[f.Name] != nil {
			continue // match key fields are set together with the match field
		}
		switch c := f.Attr.(type) {
		case *model.LengthFieldAttribute, *model.CheckSumFieldAttribute:
			// zero-initialized; recomputed or patched on the wire
		case *model.ObjectFieldAttribute:
			if f.IsRepeat {
				// empty object lists keep the zero-initialized NULL/0 pair
				continue
			}
			if c.RefPacket != nil {
				lines = append(lines, g.testAssignments(c.RefPacket, path+"."+name)...)
			}
		default:
			if f.IsRepeat {
				lines = append(lines, g.testRepeatAssignments(f, path, name)...)
				continue
			}
			if fs, ok := f.Attr.(*model.FixedStringFieldAttribute); ok {
				lines = append(lines, fmt.Sprintf("%s.%s = FC_STR(\"%s\");", path, name, strings.Repeat("a", fs.Length)))
				continue
			}
			lines = append(lines, fmt.Sprintf("%s.%s = %s;", path, name, g.cTestSingleValue(f)))
		}
	}
	return lines
}

func (g CGenerator) testRepeatAssignments(f *model.Field, path, name string) []string {
	var elems []string
	count := 0
	if fs, ok := f.Attr.(*model.FixedStringFieldAttribute); ok {
		count = fs.Length
		for i := 0; i < fs.Length; i++ {
			elems = append(elems, `FC_STR("a")`)
		}
	} else if _, ok := f.Attr.(*model.ObjectFieldAttribute); ok {
		// empty object lists keep the zero-initialized NULL/0 pair
		return nil
	} else {
		elems = strings.Split(g.cTestListValue(f), ", ")
		count = len(elems)
	}
	var lines []string
	elemType := "fc_string"
	if _, ok := f.Attr.(*model.DynamicStringFieldAttribute); !ok {
		if _, isFixed := f.Attr.(*model.FixedStringFieldAttribute); !isFixed {
			if t, ok := cBasicTypes[f.GetType()]; ok {
				elemType = t
			}
		}
	}
	lines = append(lines, fmt.Sprintf("%s %s_vals[] = { %s };", elemType, name, strings.Join(elems, ", ")))
	lines = append(lines, fmt.Sprintf("%s.%s = %s_vals;", path, name, name))
	lines = append(lines, fmt.Sprintf("%s.%s_count = %d;", path, name, count))
	return lines
}

func (g CGenerator) cTestSingleValue(f *model.Field) string {
	switch f.Attr.(type) {
	case *model.LengthFieldAttribute:
		return "0"
	}
	if v, ok := g.cPrimitiveSingleValues()[f.GetType()]; ok {
		return v
	}
	return "0"
}

func (g CGenerator) cTestListValue(f *model.Field) string {
	if v, ok := g.cPrimitiveListValues()[f.GetType()]; ok {
		return v
	}
	return "0, 0"
}

