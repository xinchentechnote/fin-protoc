func (g CGenerator) objectTypeName(pkt *model.Packet, f *model.Field) string {
	return g.cFieldTypeName(pkt, f)
}

func (g CGenerator) matchValueTypeName(value string) string {
	if sub, ok := g.binModel.PacketsMap[value]; ok {
		return g.cTypeName(sub)
	}
	return g.prefix() + strcase.ToSnake(value)
}

func (g CGenerator) arrayPrefixBytes() int {
	if n, ok := cPrefixBytes[g.GetConfig().ListLenPrefixLenType]; ok {
		return n
	}
	return 2
}

func (g CGenerator) stringPrefixBytes() int {
	if n, ok := cPrefixBytes[g.GetConfig().StringLenPrefixLenType]; ok {
		return n
	}
	return 2
}

// cPutType maps a DSL type to the suffix of the fc_buffer_put_/fc_reader_get_
// runtime functions (identical spelling for all C integer/float types).
func cPutType(t string) string {
	if t == "char" {
		return "u8"
	}
	return t
}

// GetPadding returns the effective padding (field attribute wins over the
// global configuration), normalized as a copy.
func (g CGenerator) GetPadding(f *model.Field) *model.Padding {
	padding := g.GetConfig().Padding
	if fs, ok := f.Attr.(*model.FixedStringFieldAttribute); ok {
		if fs.Padding != nil {
			padding = fs.Padding
		}
	}
	if padding == nil {
		return nil
	}
	padChar := padding.PadChar
	switch padChar {
	case "'\x00'", "'\\x00'", "'\\u0000'", "'\\0'":
		padChar = "'\\0'"
	}
	return &model.Padding{PadChar: padChar, PadLeft: padding.PadLeft}
}

func (g CGenerator) paddingIsDefault(f *model.Field) bool {
	padding := g.GetPadding(f)
	return padding == nil || padding.IsDefault()
}

// cPadChar renders the pad character as a C char literal.
func (g CGenerator) cPadChar(f *model.Field) string {
	padding := g.GetPadding(f)
	if padding == nil {
		return "' '"
	}
	inner := padding.PadChar
	if len(inner) >= 2 && inner[0] == '\'' && inner[len(inner)-1] == '\'' {
		inner = inner[1 : len(inner)-1]
	}
	if inner == "\\x00" || inner == "\x00" {
		inner = "\\0"
	}
	return "'" + inner + "'"
}

func (g CGenerator) cPadLeft(f *model.Field) bool {
	padding := g.GetPadding(f)
	return padding != nil && padding.PadLeft
}

func (g CGenerator) padCallArgs(f *model.Field, padChar string, padLeft bool) string {
	if g.paddingIsDefault(f) {
		return ""
	}
	return fmt.Sprintf(", %s, %d", padChar, boolToInt(padLeft))
}

// HasQuotes is string literal
func (g CGenerator) HasQuotes(s string) bool {
	if len(s) < 2 {
		return false
	}
	first, last := s[0], s[len(s)-1]
	return first == '"' && last == '"'
}

func boolToInt(v bool) int {
	if v {
		return 1
	}
	return 0
}

func indentLines(s string, levels int) string {
	indent := strings.Repeat("    ", levels)
	return indent + strings.ReplaceAll(s, "\n", "\n"+indent) + "\n"
}
