func (g ZigGenerator) testMatchValue(parentName string, f *model.Field, mf *model.MatchFieldAttribute) string {
	if len(mf.MatchPairs) == 0 {
		return ".{}"
	}

	matchName := mf.MatchPairs[0].Value
	subPacket := g.binModel.PacketsMap[matchName]
	if subPacket == nil {
		return ".{}"
	}
	var innerFields []string
	for _, subField := range subPacket.Fields {
		innerFields = append(innerFields,
			fmt.Sprintf(".%s = %s", g.GetFieldName(subField), g.testValue(parentName, subField)))
	}
	if len(innerFields) == 0 {
		return fmt.Sprintf(".{ .%s = .{} }", strcase.ToSnake(matchName))
	}
	return fmt.Sprintf(".{ .%s = .{ %s } }",
		strcase.ToSnake(matchName),
		strings.Join(innerFields, ", "))
}
